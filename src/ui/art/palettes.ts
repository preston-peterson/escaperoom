export function paletteVars(id: PaletteId): Record<string, string> {
  const p = palettes[id] ?? palettes.cavern;
  return {
    '--p-sky-top': p.skyTop,
    '--p-sky-bottom': p.skyBottom,
    '--p-wall-dark': p.wallDark,
    '--p-wall-mid': p.wallMid,
    '--p-wall-light': p.wallLight,
    '--p-floor': p.floor,
    '--p-glow': p.glow,
    '--p-accent': p.accent,
    '--p-water': p.water,
    '--p-fog': p.fog,
  };
}
